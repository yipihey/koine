//! Apple App Intents generated from a koine verb inventory
//! (docs/plan-koine-trust.md TR-D14).
//!
//! An app's verbs become what Siri, Shortcuts and Spotlight call, the same
//! verbs the person's own buttons and agents call, through the same
//! pipeline, as the person:
//!
//! - a verb that declares `#[impress_method(intent(title = …, phrase = …))]`
//!   becomes an `AppIntent`: a `@Parameter` per argument, `perform()`
//!   dispatching the verb through the app's verb FFI (caller
//!   `{"kind":"person","name":"app-intents"}`), a confirmation first when the
//!   verb is destructive, external or of high impact, and a dialog naming the
//!   review when the call is held for one;
//! - a kind with a verb declaring `entity(lookup)` (ids in, rows out) and one
//!   declaring `entity(search)` (a string in, rows out) becomes an
//!   `AppEntity` with an `EntityQuery` and an `EntityStringQuery`, its id and
//!   title the kind's row schema's; an intent argument the verb names as its
//!   target, of that kind, is a parameter of that entity;
//! - phrases become an `AppShortcutsProvider` (at most ten), and the files
//!   conform to `AppIntentsPackage` so intents in a SwiftPM package are found.
//!
//! App Intents are compile-time Swift types, so this writes source that an
//! app commits and checks for staleness (impress-apps' `gen-app-intents`, or
//! `<host> app-intents write`). A verb whose arguments this cannot express is
//! left out, and [`Generated::skipped`] says why — never a broken file.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use impress_service_core::{EntityRole, Impact, Kind, SafetyClass, VerbHandle};
use serde_json::Value;

/// The first line of every generated file.
pub const GENERATED_MARK: &str =
    "// Generated by koine-app-intents from the verb inventory. Do not edit; regenerate.";

/// At most this many App Shortcuts (Apple's limit).
pub const MAX_SHORTCUTS: usize = 10;

/// The app the intents are for.
#[derive(Debug, Clone)]
pub struct AppInfo {
    /// The Swift type-name prefix (`Imbib`): `ImbibIntentsPackage`, …
    pub prefix: String,
    /// The async verb-dispatch function the app's FFI exposes, called as
    /// `await f(name:argsJson:callerJson:)`.
    pub dispatch_function: String,
    /// The field of its result holding the envelope's JSON text.
    pub body_field: String,
}

impl AppInfo {
    /// The impress apps' verbs-ffi shape: `dispatchVerbAsync(name:argsJson:callerJson:)`
    /// answering `{status, bodyJson}`.
    pub fn impress(prefix: impl Into<String>) -> Self {
        Self {
            prefix: prefix.into(),
            dispatch_function: "dispatchVerbAsync".into(),
            body_field: "bodyJson".into(),
        }
    }
}

/// What was generated: files by name, and the verbs left out with why.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Generated {
    pub files: BTreeMap<String, String>,
    pub skipped: Vec<(String, String)>,
}

/// A kind's app entity: its lookup and search verbs and row fields.
#[derive(Debug, Clone)]
struct Entity {
    kind: String,
    type_name: String,
    id_field: String,
    title_field: String,
    lookup: (String, String),
    search: (String, String),
}

fn camel(text: &str) -> String {
    text.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut chars = w.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn lower_camel(text: &str) -> String {
    let upper = camel(text);
    let mut chars = upper.chars();
    match chars.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// A Swift string literal's body: escaped.
fn swift_str(text: &str) -> String {
    text.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', " ")
}

/// `${applicationName}` as App Shortcuts spell it.
fn phrase(text: &str) -> String {
    swift_str(text).replace("${applicationName}", "\\(.applicationName)")
}

/// The intent's Swift type name: `<Service without -service><Method>Intent`.
fn intent_type(verb: &VerbHandle) -> String {
    let service = verb
        .service()
        .trim_end_matches("-service")
        .trim_end_matches("_service");
    format!("{}{}Intent", camel(service), camel(verb.method()))
}

fn properties(schema: &Value) -> Vec<(String, Value, bool)> {
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    schema
        .get("properties")
        .and_then(Value::as_object)
        .map(|props| {
            props
                .iter()
                .map(|(name, prop)| {
                    (
                        name.clone(),
                        prop.clone(),
                        required.contains(&name.as_str()),
                    )
                })
                .collect()
        })
        .unwrap_or_default()
}

/// A property's JSON type, `null` aside: `("string", nullable)`.
fn json_type(prop: &Value) -> Option<(String, bool)> {
    match prop.get("type") {
        Some(Value::String(t)) => Some((t.clone(), false)),
        Some(Value::Array(types)) => {
            let names: Vec<&str> = types.iter().filter_map(Value::as_str).collect();
            let non_null: Vec<&str> = names.iter().copied().filter(|t| *t != "null").collect();
            (non_null.len() == 1).then(|| (non_null[0].to_owned(), names.contains(&"null")))
        }
        _ => None,
    }
}

/// How one argument becomes a parameter.
enum Param {
    /// A Swift type and how its value goes into the arguments.
    Plain {
        swift: String,
        encode: Encode,
    },
    Entity {
        type_name: String,
        many: bool,
    },
}

enum Encode {
    AsIs,
    Date,
}

fn param_of(prop: &Value) -> Result<Param, String> {
    let (ty, _) =
        json_type(prop).ok_or("an argument with no single JSON type (a $ref or a union)")?;
    let plain = |swift: &str| Param::Plain {
        swift: swift.into(),
        encode: Encode::AsIs,
    };
    Ok(match ty.as_str() {
        "string" if prop.get("format").and_then(Value::as_str) == Some("date-time") => {
            Param::Plain {
                swift: "Date".into(),
                encode: Encode::Date,
            }
        }
        "string" => plain("String"),
        "integer" => plain("Int"),
        "number" => plain("Double"),
        "boolean" => plain("Bool"),
        "array" => {
            let items = prop
                .get("items")
                .ok_or("an array argument with no item type")?;
            match json_type(items).map(|(t, _)| t).as_deref() {
                Some("string") => plain("[String]"),
                Some("integer") => plain("[Int]"),
                Some("number") => plain("[Double]"),
                Some("boolean") => plain("[Bool]"),
                _ => return Err("an array of objects or unions".into()),
            }
        }
        other => return Err(format!("an argument of type {other}")),
    })
}

/// The arguments a verb names as what it acts on.
fn target_args(verb: &VerbHandle) -> Vec<String> {
    let mut out: Vec<String> = verb
        .consent()
        .targets
        .map(str::to_owned)
        .into_iter()
        .collect();
    for kind in verb.effects().writes.iter().chain(verb.effects().reads) {
        if let Kind::Target(arg) | Kind::Children(arg) = kind {
            if !out.iter().any(|o| o == arg) {
                out.push((*arg).to_owned());
            }
        }
    }
    out
}

fn entities(verbs: &[VerbHandle]) -> BTreeMap<String, Entity> {
    let mut lookups: BTreeMap<String, (&VerbHandle, String)> = BTreeMap::new();
    let mut searches: BTreeMap<String, (&VerbHandle, String)> = BTreeMap::new();
    for verb in verbs {
        let (Some(role), Some(kind)) = (verb.intent().entity, verb.returns_kind()) else {
            continue;
        };
        let schema = verb.input_schema();
        let props = properties(&schema);
        match role {
            EntityRole::Lookup => {
                if let Some((name, _, _)) = props.iter().find(|(_, p, _)| {
                    json_type(p).is_some_and(|(t, _)| t == "array")
                        && p.get("items")
                            .and_then(json_type)
                            .is_some_and(|(t, _)| t == "string")
                }) {
                    lookups.insert(kind.to_owned(), (verb, name.clone()));
                }
            }
            EntityRole::Search => {
                if let Some((name, _, _)) = props
                    .iter()
                    .find(|(_, p, _)| json_type(p).is_some_and(|(t, _)| t == "string"))
                {
                    searches.insert(kind.to_owned(), (verb, name.clone()));
                }
            }
        }
    }
    let mut out = BTreeMap::new();
    for (kind, (lookup, ids_arg)) in &lookups {
        let Some((search, text_arg)) = searches.get(kind) else {
            continue;
        };
        let Some(rows) = lookup.rows() else { continue };
        out.insert(
            kind.clone(),
            Entity {
                kind: kind.clone(),
                type_name: format!("{}Entity", camel(kind)),
                id_field: rows.id.to_owned(),
                title_field: rows.title.unwrap_or(rows.id).to_owned(),
                lookup: (lookup.name().to_owned(), ids_arg.clone()),
                search: (search.name().to_owned(), text_arg.clone()),
            },
        );
    }
    out
}

fn support_file(app: &AppInfo) -> String {
    let p = &app.prefix;
    let mut s = String::new();
    let _ = writeln!(s, "{GENERATED_MARK}\n");
    s.push_str("import AppIntents\nimport Foundation\n\n");
    let _ = writeln!(
        s,
        "/// Lets Shortcuts find the intents when they live in a SwiftPM package.\npublic struct {p}IntentsPackage: AppIntentsPackage {{}}\n"
    );
    let _ = writeln!(
        s,
        r#"/// A verb that refused, as an intent's error.
public struct {p}IntentRefusal: Error, CustomLocalizedStringResourceConvertible {{
    public let code: String
    public let message: String
    public var localizedStringResource: LocalizedStringResource {{ "\(message)" }}
}}

/// Calls the app's verbs as the person, through its verb FFI.
enum {p}Verbs {{
    /// The verb's answer. A refusal throws, except `review-pending`, which
    /// is answered (the call waits for the person's approval).
    static func call(_ verb: String, _ args: [String: Any]) async throws -> Any {{
        let argsData = try JSONSerialization.data(withJSONObject: args)
        let caller = "{{\"kind\":\"person\",\"name\":\"app-intents\",\"trace_id\":\"\(UUID().uuidString)\"}}"
        let result = await {dispatch}(
            name: verb,
            argsJson: String(decoding: argsData, as: UTF8.self),
            callerJson: caller
        )
        let body = try JSONSerialization.jsonObject(
            with: Data(result.{body}.utf8),
            options: [.fragmentsAllowed]
        )
        if let object = body as? [String: Any], object["ok"] as? Bool == false {{
            let code = object["code"] as? String ?? "refused"
            if code == "review-pending" {{ return object }}
            throw {p}IntentRefusal(code: code, message: object["message"] as? String ?? code)
        }}
        return body
    }}

    /// Whether an answer is a call held for the person's approval.
    static func isPending(_ answer: Any) -> Bool {{
        (answer as? [String: Any])?["code"] as? String == "review-pending"
    }}

    /// The rows of an answer: an array, or the object's `rows`.
    static func rows(_ answer: Any) -> [[String: Any]] {{
        if let rows = answer as? [[String: Any]] {{ return rows }}
        if let object = answer as? [String: Any] {{
            if let rows = object["rows"] as? [[String: Any]] {{ return rows }}
            for value in object.values {{
                if let rows = value as? [[String: Any]] {{ return rows }}
            }}
        }}
        return []
    }}

    /// One line for a dialog.
    static func summary(_ answer: Any) -> String {{
        if let object = answer as? [String: Any] {{
            if let message = object["message"] as? String {{ return message }}
            let rows = rows(answer)
            if !rows.isEmpty {{ return "\(rows.count) result(s)" }}
        }}
        return "Done"
    }}

    static func iso8601(_ date: Date) -> String {{
        ISO8601DateFormatter().string(from: date)
    }}
}}"#,
        dispatch = app.dispatch_function,
        body = app.body_field,
    );
    s
}

fn entity_file(app: &AppInfo, entities: &BTreeMap<String, Entity>) -> String {
    let p = &app.prefix;
    let mut s = String::new();
    let _ = writeln!(s, "{GENERATED_MARK}\n");
    s.push_str("import AppIntents\nimport Foundation\n");
    for e in entities.values() {
        let t = &e.type_name;
        let _ = write!(
            s,
            r#"
/// A `{kind}` record of the app.
public struct {t}: AppEntity {{
    public static var typeDisplayRepresentation: TypeDisplayRepresentation {{ "{display}" }}
    public static var defaultQuery = {t}Query()
    public var id: String
    public var title: String
    public var displayRepresentation: DisplayRepresentation {{ DisplayRepresentation(title: "\(title)") }}

    init(id: String, title: String) {{
        self.id = id
        self.title = title
    }}

    init?(row: [String: Any]) {{
        guard let id = row["{id_field}"].map({{ "\($0)" }}) else {{ return nil }}
        self.id = id
        self.title = row["{title_field}"].map({{ "\($0)" }}) ?? id
    }}
}}

/// Finds `{kind}` records by id (`{lookup}`) and by text (`{search}`).
public struct {t}Query: EntityQuery, EntityStringQuery {{
    public init() {{}}

    public func entities(for identifiers: [String]) async throws -> [{t}] {{
        let answer = try await {p}Verbs.call("{lookup}", ["{ids_arg}": identifiers])
        return {p}Verbs.rows(answer).compactMap({t}.init(row:))
    }}

    public func entities(matching string: String) async throws -> [{t}] {{
        let answer = try await {p}Verbs.call("{search}", ["{text_arg}": string])
        return {p}Verbs.rows(answer).compactMap({t}.init(row:))
    }}

    public func suggestedEntities() async throws -> [{t}] {{
        try await entities(matching: "")
    }}
}}
"#,
            kind = e.kind,
            display = swift_str(&camel(&e.kind)),
            id_field = swift_str(&e.id_field),
            title_field = swift_str(&e.title_field),
            lookup = e.lookup.0,
            ids_arg = e.lookup.1,
            search = e.search.0,
            text_arg = e.search.1,
        );
    }
    s
}

/// The intent for `verb`, or why it cannot be one.
fn intent_source(
    app: &AppInfo,
    verb: &VerbHandle,
    entities: &BTreeMap<String, Entity>,
) -> Result<String, String> {
    let title = verb.intent().title.ok_or("not an intent")?;
    let schema = verb.input_schema();
    let targets = target_args(verb);
    let entity = verb.returns_kind().and_then(|k| entities.get(k));
    let mut params = String::new();
    let mut encode = String::new();
    for (name, prop, required) in properties(&schema) {
        if name == "adverbs" {
            continue;
        }
        let field = lower_camel(&name);
        let label = swift_str(
            &prop
                .get("description")
                .and_then(Value::as_str)
                .map(|d| d.split('.').next().unwrap_or(d).to_owned())
                .unwrap_or_else(|| camel(&name)),
        );
        let param = match (targets.contains(&name), entity) {
            (true, Some(e)) => match json_type(&prop).map(|(t, _)| t).as_deref() {
                Some("string") => Param::Entity {
                    type_name: e.type_name.clone(),
                    many: false,
                },
                Some("array") => Param::Entity {
                    type_name: e.type_name.clone(),
                    many: true,
                },
                _ => param_of(&prop).map_err(|why| format!("`{name}`: {why}"))?,
            },
            _ => param_of(&prop).map_err(|why| format!("`{name}`: {why}"))?,
        };
        let (swift, value) = match &param {
            Param::Plain { swift, encode } => (
                swift.clone(),
                match encode {
                    Encode::AsIs => "$0".to_owned(),
                    Encode::Date => format!("{}Verbs.iso8601($0)", app.prefix),
                },
            ),
            Param::Entity {
                type_name,
                many: false,
            } => (type_name.clone(), "$0.id".to_owned()),
            Param::Entity {
                type_name,
                many: true,
            } => (format!("[{type_name}]"), "$0.map(\\.id)".to_owned()),
        };
        let optional = if required { "" } else { "?" };
        let _ = writeln!(
            params,
            "    @Parameter(title: \"{label}\")\n    var {field}: {swift}{optional}\n"
        );
        if required {
            let value = value.replace("$0", &field);
            let _ = writeln!(encode, "        args[\"{name}\"] = {value}");
        } else {
            let value = value.replace("$0", "value");
            let _ = writeln!(
                encode,
                "        if let value = {field} {{ args[\"{name}\"] = {value} }}"
            );
        }
    }
    let safety = verb.safety().class;
    let impact = verb.consent().impact_for(safety);
    let confirm = matches!(safety, SafetyClass::Destructive | SafetyClass::External)
        || impact == Impact::High;
    let description = swift_str(verb.description().split('\n').next().unwrap_or(""));
    let mut s = String::new();
    let _ = write!(
        s,
        r#"
/// `{name}`: {description}
public struct {ty}: AppIntent {{
    public static var title: LocalizedStringResource = "{title}"
    public static var description = IntentDescription("{description}")

    public init() {{}}

{params}    public func perform() async throws -> some IntentResult & ProvidesDialog {{
"#,
        name = verb.name(),
        ty = intent_type(verb),
        title = swift_str(title),
    );
    if confirm {
        let _ = writeln!(
            s,
            "        try await requestConfirmation(result: .result(dialog: \"{} is a {} action. Go ahead?\"))",
            swift_str(title),
            safety
        );
    }
    let _ = write!(
        s,
        r#"        var args: [String: Any] = [:]
{encode}        let answer = try await {p}Verbs.call("{name}", args)
        if {p}Verbs.isPending(answer) {{
            return .result(dialog: "This waits for your approval in the app's review list.")
        }}
        return .result(dialog: "\({p}Verbs.summary(answer))")
    }}
}}
"#,
        p = app.prefix,
        name = verb.name(),
    );
    if !verb.consent().alternatives.is_empty() {
        // Alternatives (TR-D7) are offered in the app's review, not here yet.
        let _ = writeln!(
            s,
            "// {} offers alternatives ({}); choose them in the app's review.",
            verb.name(),
            verb.consent().alternatives.join(", ")
        );
    }
    Ok(s)
}

/// Generate the App Intents for `verbs`.
pub fn generate(verbs: &[VerbHandle], app: &AppInfo) -> Generated {
    let mut verbs: Vec<VerbHandle> = verbs.to_vec();
    verbs.sort_by(|a, b| a.name().cmp(b.name()));
    verbs.dedup_by(|a, b| a.name() == b.name());
    let entities = entities(&verbs);
    let mut out = Generated::default();
    let mut intents = String::new();
    let _ = writeln!(intents, "{GENERATED_MARK}\n");
    intents.push_str("import AppIntents\nimport Foundation\n");
    let mut shortcuts: Vec<(String, String, String)> = Vec::new();
    for verb in &verbs {
        if verb.intent().title.is_none() {
            continue;
        }
        if verb.linked().is_none() {
            out.skipped.push((
                verb.name().to_owned(),
                "a provider verb is not compiled in".into(),
            ));
            continue;
        }
        match intent_source(app, verb, &entities) {
            Ok(source) => {
                intents.push_str(&source);
                if let Some(text) = verb.intent().phrase {
                    shortcuts.push((
                        intent_type(verb),
                        phrase(text),
                        swift_str(verb.intent().title.unwrap_or_default()),
                    ));
                }
            }
            Err(why) => out.skipped.push((verb.name().to_owned(), why)),
        }
    }
    let p = &app.prefix;
    if shortcuts.len() > MAX_SHORTCUTS {
        for (ty, _, _) in shortcuts.drain(MAX_SHORTCUTS..) {
            out.skipped
                .push((ty, format!("more than {MAX_SHORTCUTS} App Shortcuts")));
        }
    }
    let mut provider = String::new();
    let _ = writeln!(provider, "{GENERATED_MARK}\n");
    provider.push_str("import AppIntents\n\n");
    let _ = writeln!(
        provider,
        "public struct {p}Shortcuts: AppShortcutsProvider {{\n    public static var appShortcuts: [AppShortcut] {{"
    );
    for (ty, text, short) in &shortcuts {
        let _ = writeln!(
            provider,
            "        AppShortcut(intent: {ty}(), phrases: [\"{text}\"], shortTitle: \"{short}\", systemImageName: \"sparkles\")"
        );
    }
    provider.push_str("    }\n}\n");
    out.files
        .insert(format!("{p}IntentsSupport.swift"), support_file(app));
    out.files
        .insert(format!("{p}Entities.swift"), entity_file(app, &entities));
    out.files.insert(format!("{p}Intents.swift"), intents);
    if !shortcuts.is_empty() {
        out.files.insert(format!("{p}Shortcuts.swift"), provider);
    }
    out
}
